    =#

    return _propose_gpu_kernel(backend, 32)(sample_dest, weight_dest, proposal, rng.state; ndrange = size(sample_dest))
end

# thread-local gpu version
function _gpu_propose(
        u::AbstractTransformProposal{TT},
        threadid,
        randstate::AbstractVector{NTuple{4, UInt32}},
    ) where {N, T, TT <: SVector{N, T}}
    return _transform(u, gpu_rand(TT, threadid, randstate))
end
