# variate form, where arguments are SVectors of scalars representing the coordinates
# NOTE: for univariate proposals, use Distributions.Univariate
abstract type CoordinateVariate <: Distributions.VariateForm end

const ProposalVariateForm = Union{Distributions.Univariate, CoordinateVariate}


"""
    AbstractProposal{T, F <: ProposalVariateForm}

Abstract supertype for proposal distributions.

# Parameters
- `T`: Element type of generated samples.
  - `T <: Real` for **univariate** proposals.
  - `T <: NTuple{N,<:Real}` for **coordinate variate** proposals.
- `F`: Variate form, either `Distributions.Univariate` or `CoordinateVariate`.

# Variate form
Unlike in `Distributions.jl`, where both cases are considered *univariate*,
we explicitly distinguish:
- **Univariate proposals** (`F == Distributions.Univariate`, `T <: Real`).
- **Coordinate variate proposals** (`F == CoordinateVariate`, `T <: NTuple{N,<:Real}`).

This distinction is important because our data layout stores multiple coordinates
inside a single `NTuple`, which is natural in physics applications where
phase-space points consist of coordinate tuples.

# Required interface
Subtypes of `AbstractProposal` must implement:

```julia
degrees_of_freedom(proposal::AbstractProposal)::Int
_rand!(rng::AbstractRNG, proposal::AbstractProposal{T}, dest::AbstractVector{T}) where {T}
```

* `degrees_of_freedom` returns the number of coordinates generated by the proposal:

  * For univariate proposals: always `1`.
  * For coordinate variate proposals: equals the tuple length `N`.

* `_rand!` generates random samples and writes them into `dest`.

# Supported destination arrays

`dest` can be a `Vector`, `CuVector`, `ROCArray`, `OneArray`, or `MtlArray`.

Depending on the RNG type, random numbers are either generated directly on device
or generated on CPU and copied to the device.
"""
abstract type AbstractProposal{T, F <: ProposalVariateForm} end
Base.broadcastable(d::AbstractProposal) = Ref(d)
Base.eltype(::AbstractProposal{T}) where {T} = T
variate_form(::AbstractProposal{T, F}) where {T, F} = F


"""

    _rand!(rng::AbstractRNG, proposal::AbstractProposal{T}, dest::AbstractVector{T}) where T

Interface function for proposal generation. The element type `T` is purposely not restricted to numbers, but should at least support `T<:NTuple{N,<:Real}`.
"""
function _rand! end

"""

    degrees_of_freedom(proposal::AbstractProposal)::Int

Interface function: return the number of coordinates generated by the proposal.
"""
function degrees_of_freedom end

# Specializations
const AbstractUnivariateProposal{T} = AbstractProposal{T, Distributions.Univariate}
degrees_of_freedom(::AbstractUnivariateProposal) = 1

const AbstractCoordinateProposal{T} = AbstractProposal{T, CoordinateVariate}


"""
    AbstractGlobalTransformProposal{T} <: AbstractCoordinateProposal{T}

Abstract supertype for **global transformation–based proposals**.

This type represents proposals where samples are generated in two stages:

1. **Unit random generation:** draw random numbers in a canonical space
   (e.g. uniform numbers in `[0,1]` or standard Gaussian samples).
2. **Global transformation:** map these unit random numbers into the target
   coordinate space via a proposal-defined transformation.

# Variate form
* Always a subtype of `AbstractCoordinateProposal{T}` with variate form `CoordinateVariate`.
* The element type `T` is typically an `SVector{N,<:Real}`, representing
  multi-coordinate phase-space points.

# Required interface
Subtypes must implement:

```julia
_global_transform!(
    proposal::AbstractGlobalTransformProposal{T},
    unit_rnd_coords::AbstractVector{T},
) where T
```

* `_global_transform!` takes `unit_rnd_coords`, a collection of unit random coordinates,
  and transforms them in place into physical coordinates according to the proposal.

# Sampling

The default `_rand!` implementation for `AbstractGlobalTransformProposal` executes:

1. `_rand!(rng, dest)` — fill `dest` with unit random coordinates.
2. `_global_transform!(proposal, dest)` — apply the global transformation in place.

!!! note
On GPUs, unit random generation and transformation may or may not be fused into
a single kernel. If they are not fused, benchmarking against a local-transform
implementation is recommended.

"""
abstract type AbstractGlobalTransformProposal{T} <: AbstractCoordinateProposal{T} end

"""

    _global_transform!(
        proposal::AbstractGlobalTransformProposal{T},
        unit_rnd_coords::AbstractVector{T}
    ) where T

Interface function for global transformations of unit random coordinates.

# Arguments

* `proposal`: an instance of a subtype of `AbstractGlobalTransformProposal`.
* `unit_rnd_coords`: vector of unit random coordinates to be transformed in place.

"""
function _global_transform! end

# TODO:
# - check if rand and transform are fused on GPU
# - if not: benchmark against local transform
function _rand!(
        rng::AbstractRNG,
        proposal::AbstractGlobalTransformProposal{TT},
        dest::AbstractVector{TT},
    ) where {T, N, TT <: SVector{N, T}}
    @inline _rand!(rng, dest)
    @inline _global_transform!(proposal, dest)

    return dest
end

"""
    AbstractLocalTransformProposal{T} <: AbstractCoordinateProposal{T}

Abstract supertype for **local transformation–based proposals**.

This type represents proposals where each coordinate vector is generated
by applying a *local transformation* to independently drawn unit random numbers.

# Variate form
* Always a subtype of `AbstractCoordinateProposal{T}` with variate form `CoordinateVariate`.
* The element type `T` is typically an `SVector{N,<:Real}`, representing
  multi-coordinate phase-space points.

# Required interface
Subtypes must implement:

```julia
_local_transform(
    proposal::AbstractLocalTransformProposal{T},
    unit_rnd_coord::T
) where T
```

* `_local_transform` maps a single unit random coordinate (of type `T`) into
  a transformed coordinate according to the proposal definition.

# Sampling

The default `_rand!` implementation for `AbstractLocalTransformProposal` executes:

1. Draws unit random coordinates with `rand(rng, TT)` for each element, where
   `TT` is an `SVector{N,<:Real}`.
2. Applies `_local_transform(proposal, unit_rnd_coord)` independently for each
   sampled unit vector.

This means that the transformation is applied *locally* and independently
for every coordinate tuple.

!!! note
This approach is straightforward but may be less efficient than the global
transform approach on GPU backends, since random generation and transformation
are not fused into a single kernel.
"""
abstract type AbstractLocalTransformProposal{T} <: AbstractCoordinateProposal{T} end

"""

    _local_transform(
        proposal::AbstractLocalTransformProposal{T},
        unit_rnd_coord::T
    ) where T

Interface function for local transformations of unit random coordinates.

# Arguments

* `proposal`: an instance of a subtype of `AbstractLocalTransformProposal`.
* `unit_rnd_coord`: a single unit random coordinate, typically an `SVector{N,<:Real}`,
  drawn from a canonical distribution (e.g. uniform in `[0,1]` or standard normal).

# Returns

* The transformed coordinate(s), of the same type as `unit_rnd_coord`, according
  to the transformation defined by `proposal`.

# Description

Applies the local transformation for a **single draw** of unit random coordinates.
This function is invoked repeatedly by `_rand!` to generate a full set of samples.
"""
function _local_transform end

# cpu version
function _rand!(
        rng::AbstractRNG,
        proposal::AbstractLocalTransformProposal{TT},
        dest::AbstractVector{TT},
    ) where {T, N, TT <: SVector{N, T}}
    isempty(dest) && return dest

    for i in eachindex(dest)
        dest[i] = _local_transform(proposal, rand(rng, TT))
    end
    return dest
end

#gpu version
function gpu_rand(
        ::Type{TT},
        u::AbstractLocalTransformProposal{TT},
        threadid,
        randstate::AbstractVector{NTuple{4, UInt32}},
    ) where {N, T, TT <: SVector{N, T}}
    return _local_transform(u, gpu_rand(TT, threadid, randstate))
end

function _rand!(
        rng::GPUArrays.RNG,
        proposal::AbstractLocalTransformProposal{TT},
        A::GPUArrays.AnyGPUArray{TT},
    ) where {N, T, TT <: SVector{N, T}}
    isempty(A) && return A
    @kernel function rand!(a, randstate)
        idx = @index(Global, Linear)
        @inbounds a[idx] =
            gpu_rand(TT, proposal, ((idx - 1) % length(randstate) + 1), randstate)
    end
    rand!(get_backend(A))(A, rng.state; ndrange = size(A))
    return A
end
