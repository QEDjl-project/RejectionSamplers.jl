### Variate forms

"""
    CoordinateVariate <: Distributions.VariateForm

Variate form where arguments are `SVector`s of scalars representing coordinates.

!!! note
    For univariate proposals, use [`Distributions.Univariate`](@ref).
"""
abstract type CoordinateVariate <: Distributions.VariateForm end

const ProposalVariateForm = Union{Distributions.Univariate, CoordinateVariate}


### Abstract base type for proposal distributions

"""
    AbstractProposalDistribution{Ts, Tw, F <: ProposalVariateForm}

Abstract supertype for all proposal distributions.

Type parameters:
- `Ts`: sample type
- `Tw`: weight type
- `F`: variate form (`Univariate` or `CoordinateVariate`)
"""
abstract type AbstractProposalDistribution{Ts, Tw, F <: ProposalVariateForm} end

Base.broadcastable(d::AbstractProposalDistribution) = Ref(d)

sample_type(::AbstractProposalDistribution{Ts}) where {Ts} = Ts
weight_type(::AbstractProposalDistribution{Ts, Tw}) where {Ts, Tw} = Tw
variate_form(::AbstractProposalDistribution{Ts, Tw, F}) where {Ts, Tw, F} = F


### Interface definitions

"""
    degrees_of_freedom(proposal::AbstractProposalDistribution) -> Int

Return the number of coordinates generated by the proposal.
"""
function degrees_of_freedom end


"""
    _propose_single(rng::AbstractRNG, proposal::AbstractProposalDistribution)

Return a single `(sample, weight)` tuple drawn from `proposal`.
"""
function _propose_single end


"""
    _propose!(
        rng::AbstractRNG,
        proposal::AbstractProposalDistribution,
        samples::AbstractVector,
        weights::AbstractVector;
        backend = KernelAbstractions.CPU(),
    )

Propose samples and weights for the given backend.

For CPU backends, falls back to `_propose_single`.
For GPU backends, must be specialized explicitly.
"""
function _propose!(
        rng::AbstractRNG, proposal::AbstractProposalDistribution,
        samples::AbstractVector, weights::AbstractVector,
        backend::KernelAbstractions.Backend
    )
    return _propose_on_device!(rng, proposal, samples, weights, backend)
end


### Default CPU implementation

function _propose_on_device!(
        rng::AbstractRNG,
        proposal::AbstractProposalDistribution,
        samples::AbstractVector,
        weights::AbstractVector,
        ::KernelAbstractions.CPU,
    )
    @inbounds for i in eachindex(samples)
        samples[i], weights[i] = _propose_single(rng, proposal)
    end
    return nothing
end


### GPU stub (for explicit specialization)

function _propose_on_device!(
        rng::GPUArrays.RNG,
        proposal::AbstractProposalDistribution,
        samples::AbstractVector,
        weights::AbstractVector,
        backend::KernelAbstractions.GPU,
    )
    throw(MethodError("_propose_on_device! not implemented for GPU backend"))
end


### Specializations

const AbstractUnivariateProposal{T} =
    AbstractProposalDistribution{T, T, Distributions.Univariate}

degrees_of_freedom(::AbstractUnivariateProposal) = 1

const AbstractCoordinateProposal{Ts, Tw} =
    AbstractProposalDistribution{Ts, Tw, CoordinateVariate}


### Transform proposals

"""
    AbstractTransformProposal{Ts, Tw} <: AbstractCoordinateProposal{Ts, Tw}

Proposal distributions that generate samples through a local transformation
of unit random coordinates.
"""
abstract type AbstractTransformProposal{Ts, Tw} <: AbstractCoordinateProposal{Ts, Tw} end


"""
    _transform(proposal::AbstractTransformProposal{T}, unit_coord::T)
        -> (sample, weight)

Transform unit random coordinates into the target sample space.
Return the transformed sample and its associated proposal weight.
"""
function _transform end


### CPU implementation

function _propose_single(rng::AbstractRNG, proposal::AbstractTransformProposal{Ts}) where {Ts}
    return _transform(proposal, rand(rng, Ts))
end


### GPU implementation

@kernel function _propose_gpu_kernel(samples, weights, proposal::AbstractTransformProposal, randstate)
    idx = @index(Global, Linear)
    sample, weight = _gpu_propose(proposal, ((idx - 1) % length(randstate) + 1), randstate)
    @inbounds samples[idx] = sample
    @inbounds weights[idx] = weight
end


function _propose_on_device!(
        rng::GPUArrays.RNG,
        proposal::AbstractTransformProposal,
        samples::AbstractVector,
        weights::AbstractVector,
        backend::KernelAbstractions.GPU,
    )
    _propose_gpu_kernel(backend, 32)(
        samples, weights, proposal, rng.state;
        ndrange = size(samples)
    )
    return nothing
end


"""
    _gpu_propose(proposal::AbstractTransformProposal{TT}, threadid, randstate)
        -> (sample, weight)

Thread-local GPU version of proposal sampling.
"""
function _gpu_propose(
        proposal::AbstractTransformProposal{TT},
        threadid,
        randstate::AbstractVector{NTuple{4, UInt32}},
    ) where {N, T, TT <: SVector{N, T}}
    return _transform(proposal, gpu_rand(TT, threadid, randstate))
end
